## Regenerate R/generated-*.R from spec/openapi.json with OpenAPI Generator.
##
## Run from the package root after data-raw/sync_spec.R changes the spec:
##
##   Rscript data-raw/generate_client.R
##
## then run roxygen2::roxygenise() and the tests. The generator version is
## pinned in openapitools.json and its settings are in openapi-config.yml.
##
## The generated classes (ApiApi, ApiClient, and one class per schema) are
## internal: this script strips their roxygen comments so nothing is exported
## or documented. The package calls them through .tm_call() in R/client.R.
##
## Requires: Node.js (for npx), Java 11+, jsonlite

cli_version <- "2.28.3"  # @openapitools/openapi-generator-cli, the npm wrapper

if (!file.exists("DESCRIPTION")) {
  stop("Run this script from the package root.", call. = FALSE)
}

generator_version <- jsonlite::fromJSON("openapitools.json")$`generator-cli`$version
upstream_sha <- trimws(readLines(file.path("spec", "UPSTREAM_SHA")))

out <- tempfile("openapi-")
status <- system2("npx", c(
  "--yes", paste0("@openapitools/openapi-generator-cli@", cli_version),
  "generate",
  "-i", file.path("spec", "openapi.json"),
  "-c", "openapi-config.yml",
  "-o", out
), stdout = FALSE)
if (status != 0) stop("OpenAPI Generator failed.", call. = FALSE)

header <- c(
  "# Generated by data-raw/generate_client.R from spec/openapi.json",
  sprintf("# (transitmatters/t-performance-dash@%s) with OpenAPI Generator %s.",
          substr(upstream_sha, 1, 12), generator_version),
  "# Do not edit by hand: rerun the script instead.",
  ""
)

tidy <- function(lines) {
  # Roxygen comments would export every class and write a man page for each.
  lines <- lines[!grepl("^\\s*#'", lines)]
  # The spec gives array parameters `default: []`, which the generator copies
  # into R as `stop = []`. That doesn't parse; NULL means the same thing here.
  lines <- gsub("(`?\\w+`?) = \\[\\]", "\\1 = NULL", lines)
  lines <- sub("\\s+$", "", lines)
  # Collapse the blank runs left behind by the removed comments.
  blank <- lines == ""
  lines <- lines[!(blank & c(TRUE, head(blank, -1)))]
  while (length(lines) && lines[[1]] == "") lines <- lines[-1]
  lines
}

unlink(Sys.glob(file.path("R", "generated-*.R")))
sources <- list.files(file.path(out, "R"), pattern = "\\.R$", full.names = TRUE)
for (src in sources) {
  dest <- file.path("R", paste0("generated-", basename(src)))
  writeLines(c(header, tidy(readLines(src, warn = FALSE))), dest)
  parse(dest)  # fail here, not at load time, if a fix-up above stops matching
}
unlink(out, recursive = TRUE)

api <- readLines(file.path("R", "generated-api_api.R"))
operations <- sub("^\\s*(\\w+) = function.*", "\\1",
                  grep("^\\s*get_\\w+ = function", api, value = TRUE))
operations <- operations[!grepl("_with_http_info$", operations)]
message("Wrote ", length(sources), " files to R/generated-*.R with ",
        length(operations), " operations:\n  ",
        paste(operations, collapse = "\n  "))
